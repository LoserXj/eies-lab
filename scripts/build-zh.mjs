#!/usr/bin/env node
// Builds the Chinese side of the site from the "zh" group that each Pages CMS form saves next to the English fields.
//   content/{publications,talks,projects,news}/<folder>/index.md  ->  index.zh.md
//   data/authors/<slug>.yaml                                       ->  data/zh/authors/<slug>.yaml
// A Chinese field left empty falls back to English; list items are matched by position (education, awards ...).
// The outputs are build products (.gitignore): run before `hugo`, in CI and for `pnpm dev`.
//   node scripts/build-zh.mjs            generate
//   node scripts/build-zh.mjs --migrate  one-off: fold committed Chinese files into the "zh" groups
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse, parseDocument, stringify } from 'yaml';

const root = new URL('..', import.meta.url).pathname;
const SECTIONS = ['publications', 'talks', 'projects', 'news'];
const AUTHORS = join(root, 'data/authors');
const AUTHORS_ZH = join(root, 'data/zh/authors');
// Team groups are picked once, in English; the Chinese page shows these names.
const GROUPS_ZH = {
	'Principal Investigator': '课题组负责人',
	'Postdoctoral Fellows': '博士后',
	'PhD Students': '博士生',
	'MPhil Students': '硕士研究生（MPhil）',
	'Research Assistants': '研究助理',
	'Affiliated Members': '编外成员',
	Alumni: '已毕业',
};
const FMT = { lineWidth: 0, flowCollectionPadding: false };
const HEADER = '# Generated by scripts/build-zh.mjs from the "zh" group of the English file. Edit that file, not this one.\n';

const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const isEmpty = (v) => v == null || v === '' || (Array.isArray(v) && v.every(isEmpty)) || (isObj(v) && Object.values(v).every(isEmpty));
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

// English value with the Chinese one laid over it; empty Chinese values keep the English one.
function overlay(en, zh) {
	if (isEmpty(zh)) return en;
	if (isObj(en) && isObj(zh)) {
		const out = { ...en };
		for (const [k, v] of Object.entries(zh)) out[k] = overlay(en[k], v);
		return out;
	}
	if (Array.isArray(en) && Array.isArray(zh) && [...en, ...zh].some(isObj)) {
		const n = Math.max(en.length, zh.length);
		return Array.from({ length: n }, (_, i) => overlay(en[i], zh[i]));
	}
	return zh;
}

// The inverse, for --migrate: only what the Chinese file changes. Lists of objects keep their positions.
function delta(en, zh) {
	if (same(en, zh)) return undefined;
	if (isObj(en) && isObj(zh)) {
		const out = {};
		for (const [k, v] of Object.entries(zh)) {
			const d = delta(en[k], v);
			if (d !== undefined) out[k] = d;
		}
		return Object.keys(out).length ? out : undefined;
	}
	if (Array.isArray(en) && Array.isArray(zh) && [...en, ...zh].some(isObj)) {
		// An unchanged item keeps its text (e.g. "Python"), so the Chinese list in the form stays readable.
		const text = (v) => Object.fromEntries(Object.entries(v).filter(([, x]) => typeof x === 'string' && !/^\d{4}-\d{2}-\d{2}/.test(x)));
		const items = zh.map((v, i) => delta(en[i], v) ?? (isObj(v) ? text(v) : {}));
		return items.some((v) => Object.keys(v).length) ? items : undefined;
	}
	return zh;
}

function splitPage(text) {
	const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
	if (!m) throw new Error('no YAML front matter');
	return { fm: m[1], body: m[2] };
}

const pages = () =>
	SECTIONS.flatMap((s) => {
		const dir = join(root, 'content', s);
		if (!existsSync(dir)) return [];
		return readdirSync(dir, { withFileTypes: true })
			.filter((d) => d.isDirectory() && existsSync(join(dir, d.name, 'index.md')))
			.map((d) => join(dir, d.name));
	});
const authors = () => (existsSync(AUTHORS) ? readdirSync(AUTHORS).filter((f) => f.endsWith('.yaml')) : []);

function generate() {
	let n = 0;
	for (const dir of pages()) {
		const { fm, body } = splitPage(readFileSync(join(dir, 'index.md'), 'utf8'));
		const { zh = {}, ...en } = parse(fm) ?? {};
		const { body: zhBody, ...zhFields } = zh ?? {};
		const out = overlay(en, zhFields);
		const text = isEmpty(zhBody) ? body : `${zhBody.trim()}\n`;
		writeFileSync(join(dir, 'index.zh.md'), `---\n${stringify(out, FMT)}${HEADER}---\n${text}`);
		n++;
	}
	rmSync(AUTHORS_ZH, { recursive: true, force: true });
	mkdirSync(AUTHORS_ZH, { recursive: true });
	for (const f of authors()) {
		const { zh = {}, ...en } = parse(readFileSync(join(AUTHORS, f), 'utf8')) ?? {};
		const out = overlay(en, zh ?? {});
		if (Array.isArray(en.user_groups)) out.user_groups = en.user_groups.map((g) => GROUPS_ZH[g] ?? g);
		writeFileSync(join(AUTHORS_ZH, f), HEADER + stringify(out, FMT));
		n++;
	}
	console.log(`build-zh: wrote ${n} Chinese files`);
}

// Moves the "zh" group to the end of the document, after the English fields.
function setZh(doc, value) {
	doc.delete('zh');
	if (value !== undefined) doc.set('zh', doc.createNode(value));
}

function migrate() {
	for (const dir of pages()) {
		const zhPath = join(dir, 'index.zh.md');
		if (!existsSync(zhPath)) continue;
		const en = splitPage(readFileSync(join(dir, 'index.md'), 'utf8'));
		const zh = splitPage(readFileSync(zhPath, 'utf8'));
		const doc = parseDocument(en.fm);
		const d = delta(doc.toJS(), parse(zh.fm)) ?? {};
		if (zh.body.trim() && zh.body.trim() !== en.body.trim()) d.body = zh.body.trim();
		setZh(doc, Object.keys(d).length ? d : undefined);
		writeFileSync(join(dir, 'index.md'), `---\n${doc.toString(FMT).trimEnd()}\n---\n${en.body}`);
		rmSync(zhPath);
		console.log(`migrated ${dir.slice(root.length)}`);
	}
	for (const f of authors()) {
		const zhPath = join(AUTHORS_ZH, f);
		if (!existsSync(zhPath)) continue;
		const doc = parseDocument(readFileSync(join(AUTHORS, f), 'utf8'));
		const { user_groups, ...zh } = parse(readFileSync(zhPath, 'utf8')) ?? {};
		setZh(doc, delta(doc.toJS(), zh));
		writeFileSync(join(AUTHORS, f), doc.toString(FMT));
		rmSync(zhPath);
		console.log(`migrated data/authors/${f}`);
	}
}

process.argv.includes('--migrate') ? migrate() : generate();
