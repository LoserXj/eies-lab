#!/usr/bin/env node
// Generates the content that Pages CMS keeps in other files. Run before `hugo` (CI, `pnpm dev`, scripts/serve.sh).
// 1. Talks and projects are edited inside each member's profile (data/authors/<slug>.yaml: talks[], projects[]).
//    Each item becomes a page bundle content/{talks,projects}/<id>/index.md, rendered by layouts/works/.
// 2. Chinese: every English field is followed by its Chinese twin with a `_zh` suffix (title / title_zh,
//    education[].degree / degree_zh, ...). An empty one falls back to English.
//      content/{publications,talks,projects,news}/<folder>/index.md  ->  index.zh.md   (body_zh replaces the text)
//      data/authors/<slug>.yaml                                       ->  data/zh/authors/<slug>.yaml
// All outputs are build products (.gitignore).
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse, stringify } from 'yaml';

const root = new URL('..', import.meta.url).pathname;
const SECTIONS = ['publications', 'talks', 'projects', 'news'];
const WORKS = ['talks', 'projects'];
const AUTHORS = join(root, 'data/authors');
const AUTHORS_ZH = join(root, 'data/zh/authors');
const ZH = '_zh';
// Team groups are picked once, in English; the Chinese page shows these names.
const GROUPS_ZH = {
	'Principal Investigator': '课题组负责人',
	'Postdoctoral Fellows': '博士后',
	'PhD Students': '博士生',
	'MPhil Students': '硕士研究生（MPhil）',
	'Research Assistants': '研究助理',
	'Affiliated Members': '编外成员',
	Alumni: '已毕业',
};
const FMT = { lineWidth: 0, flowCollectionPadding: false };
const NOTE = (from) => `# Generated by scripts/build-zh.mjs from ${from}. Edit that, not this file.\n`;

const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const isEmpty = (v) => v == null || v === '' || (Array.isArray(v) && v.every(isEmpty)) || (isObj(v) && Object.values(v).every(isEmpty));
const slugify = (s) => String(s).toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60);
const yamlFiles = (dir) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.yaml')).sort() : []);
// Front matter note goes last: Hugo guesses the front matter format from its first line.
const page = (fm, note, body) => `---\n${stringify(fm, FMT)}${note}---\n${body}`;

// The Chinese view of a value: every `x_zh` that is filled in replaces `x`, at any depth; the `_zh` keys are dropped.
function chinese(v) {
	if (Array.isArray(v)) return v.map(chinese);
	if (!isObj(v)) return v;
	const out = {};
	for (const [k, x] of Object.entries(v)) {
		if (k.endsWith(ZH)) {
			const base = k.slice(0, -ZH.length);
			if (!(base in v) && !isEmpty(x)) out[base] = chinese(x);
			continue;
		}
		const zh = v[k + ZH];
		out[k] = chinese(isEmpty(zh) ? x : zh);
	}
	return out;
}

// Talk and project bundles from the profiles. The owner comes first in `authors`, then the lab members added to the item.
function works() {
	let n = 0;
	for (const s of WORKS) {
		const dir = join(root, 'content', s);
		for (const d of readdirSync(dir, { withFileTypes: true })) if (d.isDirectory()) rmSync(join(dir, d.name), { recursive: true });
	}
	const seen = new Map();
	for (const f of yamlFiles(AUTHORS)) {
		const owner = f.replace(/\.yaml$/, '');
		const person = parse(readFileSync(join(AUTHORS, f), 'utf8')) ?? {};
		for (const s of WORKS) {
			for (const item of person[s] ?? []) {
				if (isEmpty(item?.title)) continue;
				const { id, with: others = [], body = '', ...fm } = item;
				const key = slugify(id || `${String(fm.date ?? '').slice(0, 4)}-${fm.title}`);
				const where = `data/authors/${f} (${s})`;
				if (seen.has(`${s}/${key}`)) throw new Error(`${where}: "${key}" is already used by ${seen.get(`${s}/${key}`)}; give one of them a different web address (id).`);
				seen.set(`${s}/${key}`, where);
				const out = { title: fm.title, authors: [owner, ...others.filter((o) => o && o !== owner)], owner, ...fm };
				mkdirSync(join(root, 'content', s, key), { recursive: true });
				writeFileSync(join(root, 'content', s, key, 'index.md'), page(out, NOTE(`the ${s} list in data/authors/${f}`), body ? `${body.trim()}\n` : ''));
				n++;
			}
		}
	}
	return n;
}

function chinesePages() {
	let n = 0;
	for (const s of SECTIONS) {
		const dir = join(root, 'content', s);
		if (!existsSync(dir)) continue;
		for (const d of readdirSync(dir)) {
			const file = join(dir, d, 'index.md');
			if (!existsSync(file)) continue;
			const m = readFileSync(file, 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
			if (!m) throw new Error(`${file}: no YAML front matter`);
			const { body_zh, ...fm } = parse(m[1]) ?? {};
			const text = isEmpty(body_zh) ? m[2] : `${body_zh.trim()}\n`;
			writeFileSync(join(dir, d, 'index.zh.md'), page(chinese(fm), NOTE('the *_zh fields of index.md'), text));
			n++;
		}
	}
	rmSync(AUTHORS_ZH, { recursive: true, force: true });
	mkdirSync(AUTHORS_ZH, { recursive: true });
	for (const f of yamlFiles(AUTHORS)) {
		const { talks, projects, ...en } = parse(readFileSync(join(AUTHORS, f), 'utf8')) ?? {};
		const out = chinese(en);
		if (en.name?.alternate) out.name = { ...out.name, display: en.name.alternate };
		if (Array.isArray(en.user_groups)) out.user_groups = en.user_groups.map((g) => GROUPS_ZH[g] ?? g);
		writeFileSync(join(AUTHORS_ZH, f), NOTE(`the *_zh fields of data/authors/${f}`) + stringify(out, FMT));
		n++;
	}
	return n;
}

const w = works();
console.log(`build-zh: ${w} talk/project pages, ${chinesePages()} Chinese files`);
