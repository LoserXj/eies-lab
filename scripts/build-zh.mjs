#!/usr/bin/env node
// Builds the Chinese side of the site. Every Pages CMS form keeps both languages in one file: each English
// field is followed by its Chinese twin with a `_zh` suffix (title / title_zh, education[].degree / degree_zh, ...).
//   content/{publications,talks,projects,news}/<folder>/index.md  ->  index.zh.md   (body_zh replaces the text)
//   data/authors/<slug>.yaml                                       ->  data/zh/authors/<slug>.yaml
// An empty Chinese field falls back to English. The outputs are build products (.gitignore): run before `hugo`.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse, stringify } from 'yaml';

const root = new URL('..', import.meta.url).pathname;
const SECTIONS = ['publications', 'talks', 'projects', 'news'];
const AUTHORS = join(root, 'data/authors');
const AUTHORS_ZH = join(root, 'data/zh/authors');
const ZH = '_zh';
// Team groups are picked once, in English; the Chinese page shows these names.
const GROUPS_ZH = {
	'Principal Investigator': '课题组负责人',
	'Postdoctoral Fellows': '博士后',
	'PhD Students': '博士生',
	'MPhil Students': '硕士研究生（MPhil）',
	'Research Assistants': '研究助理',
	'Affiliated Members': '编外成员',
	Alumni: '已毕业',
};
const FMT = { lineWidth: 0, flowCollectionPadding: false };
const HEADER = '# Generated by scripts/build-zh.mjs from the *_zh fields of the English file. Edit that file, not this one.\n';

const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);
const isEmpty = (v) => v == null || v === '' || (Array.isArray(v) && v.every(isEmpty)) || (isObj(v) && Object.values(v).every(isEmpty));

// The Chinese view of a value: every `x_zh` that is filled in replaces `x`, at any depth; the `_zh` keys are dropped.
function chinese(v) {
	if (Array.isArray(v)) return v.map(chinese);
	if (!isObj(v)) return v;
	const out = {};
	for (const [k, x] of Object.entries(v)) {
		if (k.endsWith(ZH)) {
			const base = k.slice(0, -ZH.length);
			if (!(base in v) && !isEmpty(x)) out[base] = chinese(x);
			continue;
		}
		const zh = v[k + ZH];
		out[k] = chinese(isEmpty(zh) ? x : zh);
	}
	return out;
}

function generate() {
	let n = 0;
	for (const s of SECTIONS) {
		const dir = join(root, 'content', s);
		if (!existsSync(dir)) continue;
		for (const d of readdirSync(dir)) {
			const file = join(dir, d, 'index.md');
			if (!existsSync(file)) continue;
			const m = readFileSync(file, 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
			if (!m) throw new Error(`${file}: no YAML front matter`);
			const { body_zh, ...fm } = parse(m[1]) ?? {};
			const text = isEmpty(body_zh) ? m[2] : `${body_zh.trim()}\n`;
			// The note goes last: Hugo guesses the front matter format from its first line.
			writeFileSync(join(dir, d, 'index.zh.md'), `---\n${stringify(chinese(fm), FMT)}${HEADER}---\n${text}`);
			n++;
		}
	}
	rmSync(AUTHORS_ZH, { recursive: true, force: true });
	mkdirSync(AUTHORS_ZH, { recursive: true });
	for (const f of existsSync(AUTHORS) ? readdirSync(AUTHORS).filter((f) => f.endsWith('.yaml')) : []) {
		const en = parse(readFileSync(join(AUTHORS, f), 'utf8')) ?? {};
		const out = chinese(en);
		if (en.name?.alternate) out.name = { ...out.name, display: en.name.alternate };
		if (Array.isArray(en.user_groups)) out.user_groups = en.user_groups.map((g) => GROUPS_ZH[g] ?? g);
		writeFileSync(join(AUTHORS_ZH, f), HEADER + stringify(out, FMT));
		n++;
	}
	console.log(`build-zh: wrote ${n} Chinese files`);
}

generate();
